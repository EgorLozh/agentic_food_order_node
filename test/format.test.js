'use strict';

// Этап 6: структурное форматирование ответов. Примеры — реальные «плоские» ответы бота
// (взяты из живого чата), на них и держим правила.
const test = require('node:test');
const assert = require('node:assert/strict');

const { formatReply } = require('../src/bot/format');

test('формат: склеенный список разворачивается по строкам', () => {
  const raw =
    'Проверьте заказ: • 1× Куриная Стандарт 320г — 340 ₽ • 1× Добрый газ. вода 0.5 — 150 ₽  ' +
    'Самовывоз: Raketa на Молодежной 107б, в 14:00 Оплата: картой Итого: 490 ₽  Всё верно?';
  assert.equal(
    formatReply(raw),
    [
      'Проверьте заказ:',
      '• 1× Куриная Стандарт 320г — 340 ₽',
      '• 1× Добрый газ. вода 0.5 — 150 ₽',
      '',
      'Самовывоз: Raketa на Молодежной 107б, в 14:00',
      'Оплата: картой',
      '',
      'Итого: 490 ₽',
      '',
      'Всё верно?',
    ].join('\n')
  );
});

test('формат: статус и поля — отдельными блоками, «Варианты:» в конце', () => {
  const raw =
    'Добавил в заказ: • Куриная Стандарт 320г — 340 ₽  Что дальше? Если нужного варианта нет, ' +
    'напишите своими словами.  Варианты: • Добавить ещё • К точке самовывоза';
  assert.equal(
    formatReply(raw),
    [
      'Добавил в заказ:',
      '• Куриная Стандарт 320г — 340 ₽',
      '',
      'Что дальше?',
      '',
      'Если нужного варианта нет, напишите своими словами.',
      '',
      'Варианты:',
      '• Добавить ещё',
      '• К точке самовывоза',
    ].join('\n')
  );
});

test('формат: правильный ответ не портится', () => {
  const raw = [
    'Проверьте заказ:',
    '• 2× Куриная Стандарт 320г — 680 ₽',
    '',
    'Самовывоз: Raketa на Молодежной 107б, в 14:00',
    'Оплата: наличными',
    'Телефон: +7 900 123-45-67',
    '',
    'Итого: 680 ₽',
    '',
    'Всё верно?',
  ].join('\n');
  assert.equal(formatReply(raw), raw);
});

test('формат: поля внутри строки выносятся, маркер списка не отрывается от пункта', () => {
  const raw = 'Забрать: Raketa на Молодежной 107б, в 14:00 • Комментарий Время: 15:30';
  const lines = formatReply(raw).split('\n');
  assert.ok(lines.includes('Время: 15:30'), formatReply(raw));
  assert.ok(lines.some((line) => line.startsWith('• Комментарий')), formatReply(raw));
});

test('формат: лишние пробелы и пустые строки схлопываются', () => {
  assert.equal(formatReply('  Заказ отменён. \n\n\n\n  Что заказываем?  '), 'Заказ отменён.\n\nЧто заказываем?');
  assert.equal(formatReply('а    б'), 'а б');
  assert.equal(formatReply(''), '');
  assert.equal(formatReply(null), '');
});

test('формат: цены и названия не меняются', () => {
  const raw = '• Свиная Биг 440г — 430 ₽ • 4 сыра — 450 ₽';
  const formatted = formatReply(raw);
  assert.ok(formatted.includes('Свиная Биг 440г — 430 ₽'));
  assert.ok(formatted.includes('4 сыра — 450 ₽'));
});
